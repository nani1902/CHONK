def _file_id(name: str) -> bytes:
    return hashlib.md5(f"chonk-fixture:{name}".encode("ascii")).digest()


@dataclass
class PageSpec:
    content: bytes
    size: tuple[float, float] = LETTER
    rotate: int = 0
    images: dict[str, Ref] | None = None
    annotations: list[Ref] | None = None
    resources: dict | None = None
    extra: dict | None = None


def _assemble(
    name: str,
    title: str,
    pages: list[PageSpec],
    document: Document | None = None,
    fonts: dict[str, Ref] | None = None,
    catalog_extra: dict | None = None,
    page_refs: list[Ref] | None = None,
) -> bytes:
    document = document or Document()
    fonts = fonts or font_resources(document)
    pages_ref = document.reserve()
    page_refs = page_refs or [document.reserve() for _ in pages]
    for page_ref, page in zip(page_refs, pages):
        content_ref = document.add(Stream({}, page.content))
        resources: dict = {"Font": dict(fonts)}
        if page.images:
            resources["XObject"] = dict(page.images)
        resources.update(page.resources or {})
        entries: dict = {
            "Type": Name("Page"),
            "Parent": pages_ref,
            "MediaBox": [0, 0, page.size[0], page.size[1]],
            "Resources": resources,
            "Contents": content_ref,
        }
        if page.rotate:
            entries["Rotate"] = page.rotate
        if page.annotations:
            entries["Annots"] = list(page.annotations)
        entries.update(page.extra or {})
        document.set(page_ref, entries)
    document.set(
        pages_ref, {"Type": Name("Pages"), "Kids": list(page_refs), "Count": len(pages)}
    )
    catalog: dict = {"Type": Name("Catalog"), "Pages": pages_ref}
    catalog.update(catalog_extra or {})
    root = document.add(catalog)
    return document.to_bytes(root, _file_id(name), info_dictionary(document, title))


def _heading(text: str, y: float, x: float = 72) -> TextLine:
    return TextLine(x, y, 18, text, "F4")


def _marker_line(page_label: str) -> TextLine:
    return TextLine(72, 36, 8, f"{SYNTHETIC_MARKER} test document - {page_label}", "F1")


def _rule(x1: float, y1: float, x2: float, y2: float, width: float = 1.0) -> bytes:
    return f"q {width} w {x1} {y1} m {x2} {y2} l S Q\n".encode("ascii")


def _box(x: float, y: float, w: float, h: float, gray: float) -> bytes:
    return f"q {gray} g {x} {y} {w} {h} re f Q\n".encode("ascii")


def _statement_page(seed: int, page_label: str) -> bytes:
    """A text-only page resembling a statement: prose, a table, rules."""
    rng = random.Random(seed)
    lines = [
        _heading(f"{SYNTHETIC_MARKER} Account Statement {seed:04d}", 720),
        TextLine(72, 696, 11, "Prepared for: Synthetic Person, 1 Example Street, Testville", "F3"),
        TextLine(72, 681, 11, f"Statement period: 2026-01-01 to 2026-01-31 (ref {seed:06d})", "F3"),
    ]
    y = 640.0
    lines.append(TextLine(72, y, 10, "Date        Description                    Amount", "F2"))
    total = 0
    for row in range(14):
        y -= 16
        amount = rng.randrange(100, 99_999)
        total += amount
        lines.append(
            TextLine(
                72,
                y,
                10,
                f"2026-01-{row + 2:02d}  Synthetic item {rng.randrange(1000, 9999)}"
                f"          {amount / 100:>10,.2f}",
                "F2",
            )
        )
    y -= 24
    lines.append(TextLine(72, y, 11, f"Total due: {total / 100:,.2f}", "F4"))
    lines.append(
        TextLine(72, y - 30, 10, "This page is synthetic. Figures come from a fixed seed so that", "F1")
    )
    lines.append(
        TextLine(72, y - 44, 10, "a digit changed during compression can be detected.", "F1")
    )
    lines.append(_marker_line(page_label))
    return (
        text_operators(lines)
        + _rule(72, 652, 540, 652, 0.75)
        + _rule(72, y + 14, 540, y + 14, 0.5)
    )


def _scan_image(seed: int, width: int, height: int, lines: list[str]) -> Image.Image:
    """A grayscale 'scanned page': paper tone, grain, and bitmap text."""
    rng = random.Random(seed)
    paper = Image.linear_gradient("L").resize((width, height)).point(
        lambda v: 236 + v // 24
    )
    grain = Image.frombytes("L", (width, height), rng.randbytes(width * height))
    grain = grain.filter(ImageFilter.GaussianBlur(1.2)).point(lambda v: 128 + (v - 128) // 3)
    page = Image.blend(paper, grain, 0.25)

    # Draw at low resolution, then scale up to mimic scanned glyph edges.
    small = Image.new("L", (width // 3, height // 3), 255)
    draw = ImageDraw.Draw(small)
    font = ImageFont.load_default()
    y = 30
    for line in lines:
        draw.text((24, y), line, fill=20, font=font)
        y += 16
    ink = small.resize((width, height), Image.Resampling.BILINEAR)
    return Image.composite(page, ink, ink.point(lambda v: 255 if v > 200 else 0))


def _photo_image(seed: int, width: int, height: int) -> Image.Image:
    """An RGB 'photograph': gradients, shapes, and fine texture."""
    rng = random.Random(seed)
    red = Image.linear_gradient("L").resize((width, height))
    green = Image.radial_gradient("L").resize((width, height))
    blue = Image.linear_gradient("L").rotate(90).resize((width, height))
    image = Image.merge("RGB", (red, green, blue))
    draw = ImageDraw.Draw(image)
    for _ in range(40):
        x, y = rng.randrange(width), rng.randrange(height)
        r = rng.randrange(8, width // 6)
        color = (rng.randrange(256), rng.randrange(256), rng.randrange(256))
        draw.ellipse((x - r, y - r, x + r, y + r), outline=color, width=3)
    texture = Image.frombytes("RGB", (width, height), rng.randbytes(width * height * 3))
    return Image.blend(image, texture.filter(ImageFilter.GaussianBlur(0.8)), 0.18)


def _jpeg(image: Image.Image, quality: int) -> bytes:
    buffer = io.BytesIO()
    image.save(buffer, format="JPEG", quality=quality, subsampling=0, optimize=False)
    return buffer.getvalue()


