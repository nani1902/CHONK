SIGNATURE_HEX_CAPACITY = 8_192
_BYTE_RANGE_PLACEHOLDER = b"[0 0000000000 0000000000 0000000000]"


def build_signed() -> bytes:
    """An approval signature (adbe.pkcs7.detached) by the disposable signer."""
    document = Document()
    fonts = font_resources(document)
    page_ref = document.reserve()
    signature = document.add(
        {
            "Type": Name("Sig"),
            "Filter": Name("Adobe.PPKLite"),
            "SubFilter": Name("adbe.pkcs7.detached"),
            "ByteRange": Raw(_BYTE_RANGE_PLACEHOLDER),
            "Contents": Raw(b"<" + b"0" * SIGNATURE_HEX_CAPACITY + b">"),
            "M": "D:20260101000000Z",
            "Name": "CHONK disposable test signer",
            "Reason": "SYNTHETIC fixture: signature-bearing input",
        }
    )
    field = document.add(
        {
            "Type": Name("Annot"),
            "Subtype": Name("Widget"),
            "FT": Name("Sig"),
            "T": "synthetic_signature",
            "V": signature,
            "Rect": [0, 0, 0, 0],
            "F": 132,
            "P": page_ref,
        }
    )
    acroform = document.add({"Fields": [field], "SigFlags": 3})
    content = text_operators(
        [
            _heading(f"{SYNTHETIC_MARKER} signed agreement", 720),
            TextLine(72, 690, 11, "Agreed amount: 2,500.00 (invented).", "F1"),
            _marker_line("page 1 of 1"),
        ]
    )
    unsigned = _assemble(
        "signed-pkcs7",
        "SYNTHETIC signed",
        [PageSpec(content, annotations=[field])],
        document=document,
        fonts=fonts,
        catalog_extra={"AcroForm": acroform},
        page_refs=[page_ref],
    )

    contents_start = unsigned.index(b"<" + b"0" * SIGNATURE_HEX_CAPACITY + b">")
    contents_end = contents_start + SIGNATURE_HEX_CAPACITY + 2
    byte_range = (0, contents_start, contents_end, len(unsigned) - contents_end)
    placed = f"[0 {byte_range[1]:010d} {byte_range[2]:010d} {byte_range[3]:010d}]".encode("ascii")
    assert len(placed) == len(_BYTE_RANGE_PLACEHOLDER)
    prepared = unsigned.replace(_BYTE_RANGE_PLACEHOLDER, placed, 1)
    signed_data = prepared[:contents_start] + prepared[contents_end:]
    der = detached_pkcs7(signed_data)
    hex_signature = der.hex().upper().encode("ascii")
    if len(hex_signature) > SIGNATURE_HEX_CAPACITY:
        raise ValueError("signature placeholder is too small")
    hex_signature = hex_signature.ljust(SIGNATURE_HEX_CAPACITY, b"0")
    return prepared[: contents_start + 1] + hex_signature + prepared[contents_end - 1 :]


