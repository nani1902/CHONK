def build_outline() -> bytes:
    """The twelve-page statement with a two-entry outline (bookmarks)."""
    pages = _multipage_pages()
    document = Document()
    fonts = font_resources(document)
    page_refs = [document.reserve() for _ in pages]
    outlines = document.reserve()
    first = document.reserve()
    second = document.reserve()
    document.set(
        first,
        {"Title": "Synthetic section A", "Parent": outlines, "Next": second,
         "Dest": [page_refs[0], Name("Fit")]},
    )
    document.set(
        second,
        {"Title": "Synthetic section B", "Parent": outlines, "Prev": first,
         "Dest": [page_refs[6], Name("Fit")]},
    )
    document.set(
        outlines, {"Type": Name("Outlines"), "First": first, "Last": second, "Count": 2}
    )
    return _assemble(
        "outline",
        "SYNTHETIC statement with outline",
        pages,
        document=document,
        fonts=fonts,
        catalog_extra={"Outlines": outlines, "PageMode": Name("UseOutlines")},
        page_refs=page_refs,
    )


def build_text_tiny() -> bytes:
    """Small type, hairlines, and a barcode-like pattern (local detail)."""
    rng = random.Random(7)
    lines = [_heading(f"{SYNTHETIC_MARKER} fine print sample", 720)]
    y = 690.0
    for size in (6, 5, 4.5, 4, 3.5):
        for _ in range(3):
            digits = " ".join(f"{rng.randrange(10_000):04d}" for _ in range(6))
            lines.append(TextLine(72, y, size, f"{size}pt ref {digits}", "F1"))
            y -= size + 3
        y -= 6
    lines.append(
        TextLine(72, y - 10, 5, "Footnote 1: SYNTHETIC terms apply to invented accounts only.", "F3")
    )
    lines.append(_marker_line("page 1 of 1"))
    content = text_operators(lines)
    for i in range(30):
        content += _rule(72, 420 - i * 4, 300, 420 - i * 4, 0.1 + (i % 5) * 0.05)
    x = 340.0
    for _ in range(70):
        width = rng.choice((0.5, 0.75, 1.0, 1.5, 2.0))
        content += _box(x, 300, width, 120, 0)
        x += width + rng.choice((0.5, 1.0, 1.5))
    return _assemble("text-tiny", "SYNTHETIC fine print", [PageSpec(content)])


