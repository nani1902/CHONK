"""The synthetic PDF regression corpus.

Every fixture is generated from code in this package: no document in the
corpus is copied from a customer, an applicant, or the internet. Visible text
uses the word SYNTHETIC and invented values so that any extract of a fixture
is recognizable as test data.

Each ``FixtureSpec`` records the fixture's intent, the validation-matrix
family it serves (docs/product/VALIDATION.md section 2), the document
features it carries, and the behavior of the baseline ``pdf_compressor.py``
it is meant to capture.
"""

