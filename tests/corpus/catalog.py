def _encrypt(plain: bytes, user_password: str) -> bytes:
    """RC4-128 keeps output reproducible: AES would draw random IVs."""
    writer = PdfWriter(clone_from=PdfReader(io.BytesIO(plain)))
    writer.encrypt(
        user_password=user_password,
        owner_password=OWNER_PASSWORD,
        algorithm="RC4-128",
    )
    buffer = io.BytesIO()
    writer.write(buffer)
    return buffer.getvalue()


def build_encrypted_user_password() -> bytes:
    return _encrypt(build_already_small(), USER_PASSWORD)


def build_encrypted_owner_only() -> bytes:
    """Encrypted with an empty user password: opens without prompting."""
    return _encrypt(build_already_small(), "")


